At most stadiums, fans release balloons during the 7th inning stretch — a colorful, chaotic tradition called *jet balloon* (ジェット風船). The entire stadium fills with hundreds of balloon rockets. Some stadiums sell them; others require you to bring your own.

**Important:** Some stadiums have moved away from this tradition for environmental reasons, so check in advance.

