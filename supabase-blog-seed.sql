## Cultural Experiences

### 6. Watch Morning Practice at a Sumo Stable

Sumo tournaments happen six times a year, but sumo training happens every morning. Several stables (heya) in Tokyo allow visitors to observe morning practice sessions (asageiko), where wrestlers train from around 6–10 AM. You sit silently on the floor and watch as athletes drill techniques, spar, and prepare for the day.

