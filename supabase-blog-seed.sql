Unlike MLB, where cheering is spontaneous and individual, NPB cheering is highly organized and collective. Each batter has their own chant — a song that the entire cheering section sings in unison, often with choreographed arm movements, towel waving, or clapping patterns.

The cheer leaders (ouendan) stand at the front of the outfield section with trumpets and megaphones, directing the crowd. It''s part concert, part sporting event, and part community ritual.

